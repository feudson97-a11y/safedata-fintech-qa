"""
LLM adapter: turns the aggregates-only QA report into a short Markdown summary for data stewards.

Opt-in only (``safedata run --engine langgraph --ai-summary``). Only ``qa_report.json`` is sent, and
that report holds aggregates and gate outcomes, never row-level values. The Anthropic SDK is
imported lazily so the core package never depends on it.
"""

from __future__ import annotations

import json
import os
from typing import Any, Final

from safedata.domain.exceptions import ConfigurationError

DEFAULT_MODEL: Final = "claude-sonnet-4-5"
MODEL_ENV_VAR: Final = "SAFEDATA_SUMMARY_MODEL"

SYSTEM_PROMPT: Final = (
    "You are a data-quality analyst at a fintech company. You receive the JSON audit report of a PII "
    "masking and data-quality pipeline run. Write a concise Markdown summary (max 200 words) for a "
    "data steward with these sections: '## Verdict' (one sentence: published or withheld, and why), "
    "'## Key figures' (rows, quarantine rate, reconciliation), '## Top issues' (the most frequent "
    "validation rules, most frequent first) and '## Recommended actions' (at most 3 bullets). "
    "Use only facts present in the report; never invent numbers."
)


class ClaudeSummarizer:
    """Callable ``report -> markdown`` backed by the Anthropic Messages API."""

    def __init__(self, model: str | None = None, client: Any | None = None, max_tokens: int = 800) -> None:
        self.model = model or os.environ.get(MODEL_ENV_VAR) or DEFAULT_MODEL
        self.max_tokens = max_tokens
        self._client = client

    def ensure_ready(self) -> Any:
        """Fail fast (ConfigurationError) if the SDK or API key is missing; returns the client."""
        if self._client is None:
            try:
                import anthropic  # lazy: optional dependency
            except ImportError as exc:
                raise ConfigurationError(
                    'AI summary requires the optional extra: pip install "safedata-fintech-qa[agentic]"'
                ) from exc
            if not os.environ.get("ANTHROPIC_API_KEY"):
                raise ConfigurationError("AI summary requires the ANTHROPIC_API_KEY environment variable")
            self._client = anthropic.Anthropic()
        return self._client

    def __call__(self, report: dict[str, Any]) -> str:
        message = self.ensure_ready().messages.create(
            model=self.model,
            max_tokens=self.max_tokens,
            system=SYSTEM_PROMPT,
            messages=[{"role": "user", "content": json.dumps(report, default=str)}],
        )
        text = "".join(block.text for block in message.content if getattr(block, "type", "") == "text").strip()
        if not text:
            raise ValueError("empty summary returned by the model")
        return f"<!-- Generated by {self.model}; review before sharing. -->\n\n{text}\n"
